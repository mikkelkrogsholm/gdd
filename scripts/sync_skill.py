#!/usr/bin/env python3
"""Synchronize exact authoritative reference copies into the portable GDD skill."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit


CORE_REFERENCES = (
    "AGENTS.md", "GDD.md", "SPEC.md", "WORKFLOW.md", "VALIDATOR.md",
    "GRAPHIFY.md", "VIEWER.md", "HOST.md", "agents/gdd-lead.md", "agents/gdd-worker.md",
    "docs/inspection.md",
    "docs/model-diff.md",
)
COPY_DIRECTORY = Path("references/gdd")
INDEX_PATH = Path("references/source-index.json")
CATALOG_PATH = Path("references/catalog.md")
LINK_PATTERN = re.compile(r"\]\(([^)]+)\)")


def source_paths(root: Path) -> list[str]:
    """Keep the normative corpus and required routed host guidance complete."""
    paths = set(CORE_REFERENCES)
    paths.update(path.relative_to(root).as_posix()
                 for directory in ("standard", "schemas")
                 for path in (root / directory).rglob("*") if path.is_file())
    return sorted(paths)


def repository_only_links(root: Path, sources: set[str]) -> list[dict[str, str]]:
    """Index optional citations without rewriting exact authoritative prose."""
    citations = []
    for source in sorted(sources):
        if not source.endswith(".md"):
            continue
        for href in LINK_PATTERN.findall((root / source).read_text(encoding="utf-8")):
            href = href.strip().strip("<>")
            url = urlsplit(href)
            if url.scheme or not url.path:
                continue
            target = (root / source).parent / unquote(url.path)
            try:
                relative = target.resolve().relative_to(root.resolve()).as_posix()
            except ValueError as exc:
                raise ValueError(f"Reference escapes the source repository: {source}: {href}") from exc
            if not target.is_file():
                raise ValueError(f"Missing source reference: {source}: {href}")
            if relative not in sources:
                entry = {"from": source, "href": href, "source_target": relative,
                         "role": "optional-repository-reference"}
                if entry not in citations:
                    citations.append(entry)
    return citations


def generated_assets(root: Path, origin: dict) -> dict[Path, bytes]:
    paths = source_paths(root)
    assets = {}
    entries = []
    for source in paths:
        data = (root / source).read_bytes()
        destination = COPY_DIRECTORY / source
        assets[destination] = data
        entries.append({"path": destination.as_posix(), "source": source,
                        "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)})
    optional = repository_only_links(root, set(paths))
    index = {"format": "gdd-skill-assets/1", "origin": origin,
             "files": entries, "repository_only_links": optional}
    assets[INDEX_PATH] = (json.dumps(index, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    catalog = [
        "# Bundled reference catalog", "",
        "Generated by `scripts/sync_skill.py`; do not edit generated copies or this catalog.",
        "The routed GDD guidance, normative chapters, role guides, and schemas below",
        "are exact copies of the authoritative repository files. All are available",
        "when this skill folder is installed alone. Read only the relevant material.", "",
        "The source index records per-file SHA-256 and byte sizes. It also records the",
        "source repository and Git base when known; the hashes identify actual copied",
        "working-tree bytes, including changes after that base. This is provenance and",
        "drift detection, not a signature, authorization, or new execution evidence.", "",
        "| Source | Bundled copy |", "| --- | --- |",
    ]
    catalog.extend(f"| `{source}` | [{source}](gdd/{source}) |" for source in paths)
    catalog.extend(["", "## Optional repository references", "",
                    "Exact copies retain informational links to source code, examples,",
                    "historical evidence, research, and compatibility fixtures. Those",
                    "optional links are repository-relative and are not bundled. Resolve",
                    "them in the original repository at the recorded base or by their",
                    "actual per-file revision; do not treat missing history as current evidence.",
                    "The complete source/target list is in [source-index.json](source-index.json).", ""])
    catalog.extend(f"- `{target}`" for target in sorted({link["source_target"] for link in optional}))
    catalog.extend(["", "## Integrity and maintenance", "",
                    "After standalone installation, run `python3 scripts/verify_assets.py`",
                    "from the skill directory to check bundled hashes. This needs no CLI",
                    "or source checkout and confirms local integrity, not upstream freshness.", "",
                    "In the source repository, run `python3 scripts/sync_skill.py` after",
                    "changing authoritative documents, then `python3 scripts/sync_skill.py --check`",
                    "to compare copies, index, and catalog to their maintained sources.", ""])
    assets[CATALOG_PATH] = "\n".join(catalog).encode("utf-8")
    return assets


def sync(root: Path, *, check: bool = False, repository: str | None = None,
         git_base_revision: str | None = None) -> list[str]:
    skill = root / "skills/gdd"
    previous = skill / INDEX_PATH
    origin = json.loads(previous.read_text(encoding="utf-8")).get("origin", {}) if previous.exists() else {}
    origin = {"repository": repository if repository is not None else origin.get("repository"),
              "git_base_revision": git_base_revision if git_base_revision is not None else origin.get("git_base_revision"),
              "revision_basis": "Working tree based on the recorded Git base; per-file SHA-256 identifies copied bytes, including later edits."}
    expected = generated_assets(root, origin)
    directory = skill / COPY_DIRECTORY
    existing = {path.relative_to(skill) for path in directory.rglob("*") if path.is_file()}
    obsolete = existing - set(expected)
    differences = [f"Obsolete generated reference: {path}" for path in sorted(obsolete)]
    for relative, data in expected.items():
        destination = skill / relative
        if not destination.is_file() or destination.read_bytes() != data:
            differences.append(f"Generated asset differs: {relative}")
            if not check:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
    if not check:
        for relative in obsolete:
            (skill / relative).unlink()
    return differences


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1],
                        help="Source repository root (defaults to this script's repository)")
    parser.add_argument("--check", action="store_true", help="Check freshness without writing files")
    parser.add_argument("--repository", help="Source repository URL; preserve recorded value when omitted")
    parser.add_argument("--git-base-revision", help="Known source Git base; per-file hashes identify later edits")
    args = parser.parse_args()
    try:
        differences = sync(args.root.resolve(), check=args.check,
                           repository=args.repository, git_base_revision=args.git_base_revision)
    except (OSError, ValueError) as exc:
        print(f"Skill synchronization failed: {exc}", file=sys.stderr)
        return 1
    if args.check and differences:
        print("\n".join(differences), file=sys.stderr)
        return 1
    print("Skill assets are current." if args.check else "Skill assets synchronized.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
