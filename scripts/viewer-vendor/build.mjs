import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const directory = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(directory, "../../gdd_validator/viewer/vendor");
const check = process.argv.includes("--check");
assert(process.argv.slice(2).every((value) => value === "--check"), "Unknown build argument");
const read = (name) => readFile(path.join(directory, name), "utf8");
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const lockText = await read("package-lock.json");
const lock = JSON.parse(lockText);
const packageNames = ["cytoscape", "cytoscape-fcose", "cose-base", "layout-base"];
const embeddedNames = ["heap", "lodash", "gl-matrix"];
const upstreamEmbedded = JSON.parse(await read("cytoscape-embedded-dependencies.json"));
const licenseFiles = new Map();
const dependency = async (name, licenseFile = "LICENSE") => {
  const metadata = JSON.parse(await read(`node_modules/${name}/package.json`));
  const pinned = lock.packages[`node_modules/${name}`];
  assert.equal(metadata.version, pinned.version, `Installed ${name} differs from lock`);
  const license = await read(`node_modules/${name}/${licenseFile}`);
  const licensePath = `licenses/${name}.txt`;
  licenseFiles.set(licensePath, license.trimEnd() + "\n");
  return {
    name,
    version: metadata.version,
    license: metadata.license,
    source: pinned.resolved,
    integrity: pinned.integrity,
    license_file: licensePath,
    license_sha256: sha256(licenseFiles.get(licensePath)),
  };
};
const dependencies = [];
for (const name of [...packageNames, ...embeddedNames]) {
  dependencies.push(await dependency(name, name === "gl-matrix" ? "LICENSE.md" : "LICENSE"));
}
for (const name of embeddedNames) {
  const pinned = lock.packages[`node_modules/${name}`];
  assert.equal(pinned.version, upstreamEmbedded.dependencies[name].version, `Embedded ${name} differs from upstream lock`);
  assert.equal(pinned.integrity, upstreamEmbedded.dependencies[name].integrity, `Embedded ${name} integrity differs from upstream lock`);
}
assert.equal(dependencies[0].version, "3.34.4");
assert.equal(dependencies[1].version, "2.2.0");

// The package also embeds modified JamaJS SVD code under Apache-2.0.
const layoutSource = await read("node_modules/layout-base/layout-base.js");
const svdNotice = layoutSource.match(/\/\* Below singular value decomposition[\s\S]*?\*\/\s*\/\*([\s\S]*?)\*\//);
assert(svdNotice && svdNotice[1].includes("END OF TERMS AND CONDITIONS"), "Missing upstream SVD notice");
const svdLicense = svdNotice[0].replace(/^\/\* /, "").replace(/\*\/\s*\/\*/, "").replace(/\*\/$/, "");
licenseFiles.set("licenses/jamajs-svd.txt", svdLicense.split("\n").map((line) => line.trimEnd()).join("\n").trim() + "\n");

// Preserve attributions embedded in Cytoscape's published distribution.
const cytoscapeSource = await read("node_modules/cytoscape/dist/cytoscape.esm.mjs");
const componentNotices = [
  "Embeddable Minimum Strictly-Compliant Promises/A+ 1.1.1 Thenable",
  "Copyright (c) 2013-2014 Ralf S. Engelschall (http://engelschall.com)",
  "Event object based on jQuery events, MIT license (https://jquery.org/license/)",
  "Bezier curve function generator. Copyright Gaetan Renaudeau. MIT License.",
  "Runge-Kutta spring physics function generator. Adapted from Framer.js, copyright Koen Bok. MIT License.",
];
for (const fragment of ["Ralf S. Engelschall", "Event object based on jQuery events", "Copyright Gaetan Renaudeau", "copyright Koen Bok"]) {
  assert(cytoscapeSource.includes(fragment), `Missing upstream component attribution: ${fragment}`);
}
const cytoscapeLicense = await read("node_modules/cytoscape/LICENSE");
const mitTerms = cytoscapeLicense.slice(cytoscapeLicense.indexOf("Permission is hereby granted"));
licenseFiles.set("licenses/cytoscape-embedded-components.txt", componentNotices.join("\n") + "\n\n" + mitTerms.trimEnd() + "\n");

const notice = [
  "GDD viewer browser bundle: Cytoscape.js 3.34.4 and cytoscape-fcose 2.2.0.",
  "Generated by scripts/viewer-vendor/build.mjs. Retain these third-party notices.",
  "Cytoscape's legacy global-object fallback is replaced with globalThis for strict CSP.",
  ...[...licenseFiles].map(([name, text]) => `\n--- ${name} ---\n${text}`),
].join("\n").trimEnd();
assert(!notice.includes("*/"), "A license notice cannot terminate the bundle comment");
licenseFiles.set("THIRD-PARTY-NOTICES.txt", notice + "\n");

const fallback = "freeGlobal || freeSelf || Function('return this')()";
assert.equal(cytoscapeSource.split(fallback).length, 2, "Unexpected upstream global-object fallback");
const result = await esbuild.build({
  absWorkingDir: directory,
  entryPoints: ["entry.js"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  supported: { "template-literal": false },
  charset: "ascii",
  minify: true,
  sourcemap: false,
  legalComments: "none",
  metafile: true,
  banner: { js: `/*!\n${notice}\n*/` },
  plugins: [{
    name: "strict-csp-global-object",
    setup(build) {
      build.onLoad({ filter: /cytoscape\.esm\.mjs$/ }, () => ({
        contents: cytoscapeSource.replace(fallback, "freeGlobal || freeSelf || globalThis"),
        loader: "js",
      }));
    },
  }],
});
const bundle = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
assert(!/<\/script/i.test(bundle), "Bundle may terminate an HTML script element");
assert(!/\beval\s*\(|\bFunction\s*\(|\bnew\s+(?:Worker|SharedWorker)\s*\(/.test(bundle), "Bundle contains dynamic code generation or workers");
assert(!/\bfetch\s*\(|\bXMLHttpRequest\b|\bWebSocket\b|\bimport\s*\(/.test(bundle), "Bundle contains a network or dynamic module loader");

const inputs = [];
for (const name of Object.keys(result.metafile.inputs).sort()) {
  inputs.push({ path: name, sha256: sha256(await read(name)) });
}
const manifest = {
  format: "gdd-viewer-vendor/0.1",
  bundle: { path: "cytoscape-fcose.js", sha256: sha256(bundle), bytes: Buffer.byteLength(bundle) },
  build: {
    tool: "esbuild",
    version: esbuild.version,
    command: "npm ci --ignore-scripts && npm run build",
    directory: "scripts/viewer-vendor",
    lockfile_sha256: sha256(lockText),
    entry_sha256: sha256(await read("entry.js")),
    script_sha256: sha256(await read("build.mjs")),
    format: "iife",
    target: "es2020",
    supported: { "template-literal": false },
    minify: true,
    patches: [{
      input: "node_modules/cytoscape/dist/cytoscape.esm.mjs",
      find: fallback,
      replace: "freeGlobal || freeSelf || globalThis",
      reason: "Remove legacy dynamic-code global lookup under strict hash CSP.",
    }],
  },
  dependencies: dependencies.filter(({ name }) => packageNames.includes(name)),
  embedded_dependencies: dependencies.filter(({ name }) => embeddedNames.includes(name)),
  embedded_dependency_provenance: {
    description: "Versions of dependencies already embedded in Cytoscape's published ESM distribution; not bundled a second time.",
    source: upstreamEmbedded.source,
    source_sha256: upstreamEmbedded.sha256,
    extract: "scripts/viewer-vendor/cytoscape-embedded-dependencies.json",
  },
  additional_notices: ["licenses/jamajs-svd.txt", "licenses/cytoscape-embedded-components.txt"],
  inputs,
};
const files = new Map([
  ["cytoscape-fcose.js", bundle],
  ["manifest.json", JSON.stringify(manifest, null, 2) + "\n"],
  ...licenseFiles,
]);
for (const [name, contents] of files) {
  const file = path.join(output, name);
  if (check) {
    assert.equal(await readFile(file, "utf8"), contents, `Vendored file is stale: ${name}`);
  } else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, contents);
  }
}
console.log(`${check ? "Verified" : "Built"} ${manifest.bundle.path}: ${manifest.bundle.bytes} bytes, SHA-256 ${manifest.bundle.sha256}`);
